import { chromium } from "playwright";
import path from "node:path";

const browser = await chromium.launch({ channel: "chrome", headless: true });
const page = await browser.newPage();
page.on("pageerror", (e) => console.log("PAGEERROR", e.message));
await page.goto("http://localhost:5173/video", { waitUntil: "networkidle" });
await page.setInputFiles('input[type="file"]', path.resolve("../../Sample_videos/fire_2.mp4"));
await page.waitForTimeout(1500);
const analyses = await page.locator('input[type="number"]').first().inputValue();
console.log("AUTO_ANALYSE_SECONDS", analyses);
await page.getByRole("button", { name: /run detection/i }).click();
await page.getByText("first alarm", { exact: false }).waitFor({ timeout: 240000 });
console.log("RESULT_VISIBLE");
await page.evaluate(() => { const v = document.querySelector("video"); if (v) v.currentTime = 65; });
await page.waitForTimeout(1500);
const labels = await page.locator("div.pointer-events-none > div.absolute.border-2 > span").allInnerTexts();
console.log("LABELS_AT_65", labels);
console.log("FIRE_BOXES", labels.filter((l) => l.toLowerCase().startsWith("fire")).length);
await page.screenshot({ path: "../artifacts/frontend_fire_at_65.png", fullPage: true });
await page.evaluate(() => { const v = document.querySelector("video"); if (v) v.currentTime = 75; });
await page.waitForTimeout(800);
const beyond = await page.getByText(/No analysis beyond/i).count();
console.log("BEYOND_WARNING", beyond);
await browser.close();
